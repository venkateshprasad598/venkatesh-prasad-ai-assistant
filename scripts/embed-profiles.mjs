// Copies the profile files into a JS module so the Netlify Function can bundle them.
// Runs during the Netlify build (see "build:netlify" in package.json).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const profiles = {
  recruiter: readFileSync(path.join(root, "profile.md"), "utf8"),
  friend: readFileSync(path.join(root, "profile.personal.md"), "utf8"),
};

const outDir = path.join(root, "netlify", "generated");
mkdirSync(outDir, { recursive: true });
writeFileSync(
  path.join(outDir, "profiles.js"),
  `// Generated by scripts/embed-profiles.mjs. Do not edit.\nexport const PROFILES = ${JSON.stringify(profiles, null, 2)};\n`,
);
console.log("Embedded profiles into netlify/generated/profiles.js");
